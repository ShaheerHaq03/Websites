export const statusCodes: StatusCode[] = rows.map(
  ([code, name, description, example, guidance]) => ({
    code,
    name,
    description,
    example,
    guidance,
    standard: true,
  }),
);
export function searchStatuses(query = '', family = 'all') {
  const q = query.trim().toLowerCase();
  return statusCodes.filter(
    (item) =>
      (family === 'all' || String(item.code).startsWith(family)) &&
      `${item.code} ${item.name} ${item.description} ${item.example} ${item.guidance}`
        .toLowerCase()
        .includes(q),
  );
}
